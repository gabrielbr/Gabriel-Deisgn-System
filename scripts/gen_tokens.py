#!/usr/bin/env python3
"""Generate every platform file from tokens/tokens.json.

    python3 scripts/gen_tokens.py            # write generated/ and DESIGN.md's frontmatter
    python3 scripts/gen_tokens.py --check    # exit 1 if anything on disk differs (CI)

Outputs (commit them with the tokens change):
  generated/uikit/UiTokens.java         drop-in for NotTheOmiAIApp ui-kit (br.gabriel.ui)
  generated/pulseloop/GTokens.kt        Compose values for PulseLoop (com.pulseloop.ui.theme)
  generated/web/uikit.css               CSS custom properties, light + dark, for prototypes
  generated/web/pulseloop.css           CSS custom properties, dark
  DESIGN.md                             the YAML frontmatter only; the prose is hand-written
"""
import pathlib
import sys

from tokens_lib import ROOT, argb, camel, colour_map, const, load, num, resolve

HEADER = "GENERATED by Gabriel-Design-System scripts/gen_tokens.py from tokens/tokens.json v{v} — do not edit."


# ---- uikit: Java, byte-compatible with NotTheOmiAIApp's former scripts/gen_ui_tokens.py --------

def uikit_java(t):
    r = resolve(t, "uikit")
    layer = t["layers"]["uikit"]
    out = [f"// {HEADER.format(v=t['version'])}", "package br.gabriel.ui;", "", "/**",
           " * Design tokens shared by GVoice and GMind. Values are dp / sp unless named otherwise. Every colour",
           " * has a light and a {@code _DARK} value; read the pair through {@link #color(android.content.Context, int, int)}.",
           " */", "public final class UiTokens {", "    private UiTokens() {}", "",
           "    // Colours (ARGB). *_DARK is the dark-theme value."]
    names = []
    for tok in r["color"]:
        v, n = tok["value"], const(tok["name"])
        names.append(n)
        if isinstance(v, str) and v.startswith("{"):
            ref = const(v.strip("{}"))
            out += [f"    /** {tok.get('usage', '')} */",
                    f"    public static final int {n} = {ref}; // alias",
                    f"    public static final int {n}_DARK = {ref}_DARK;"]
            continue
        light = v if isinstance(v, str) else v["light"]
        dark = light if isinstance(v, str) else v.get("dark", light)
        note = tok.get("usage", "")
        if tok.get("pair"):
            note += f" Shares its light value with another token: read it as color(context, {n}, {n}_DARK), never through dark(int)."
        out += [f"    /** {note} */",
                f"    public static final int {n} = {argb(light)};",
                f"    public static final int {n}_DARK = {argb(dark)};"]
    out += ["", "    /** The light tokens in order, and their dark values, so a light token can be looked up ({@link #dark(int)}). */",
            "    static final int[] LIGHT = {" + ", ".join(names) + "};",
            "    static final int[] DARK = {" + ", ".join(n + "_DARK" for n in names) + "};",
            "", "    // Type (sp). Family is Ubuntu Mono throughout."]
    for group in layer["type"]:
        for st in group["styles"]:
            n = const("text_" + st["name"])
            out += [f"    public static final int {n}_SIZE = {num(st['fontSize'])};",
                    f"    public static final int {n}_LINE = {num(st['lineHeight'])};",
                    f"    public static final boolean {n}_BOLD = {str(int(st.get('fontWeight', 400)) >= 700).lower()};"]
    for fam in ("spacing", "radius", "size", "motion"):
        out += ["", f"    // {fam.capitalize()} ({'ms' if fam == 'motion' else 'dp'})"]
        for tok in r[fam]:
            out += [f"    /** {tok.get('usage', '')} */",
                    f"    public static final int {const(tok['name'])} = {num(tok['value'])};"]
    out += ["", "    /** The theme's value for a colour pair: {@code dark} when the context is in the dark theme, else {@code light}. */",
            "    public static int color(android.content.Context context, int light, int dark) {",
            "        return Theme.dark(context) ? dark : light;", "    }", "",
            "    /** The dark value of a light token, or the value itself when it is not a token. */",
            "    public static int dark(int light) {",
            "        for (int i = 0; i < LIGHT.length; i++) if (LIGHT[i] == light) return DARK[i];",
            "        return light;", "    }", "}"]
    return "\n".join(out) + "\n"


# ---- pulseloop: Kotlin / Compose -----------------------------------------------------------------

def kdoc(text):
    return f"    /** {text} */" if text else None


def pulseloop_kt(t):
    r = resolve(t, "pulseloop")
    layer = t["layers"]["pulseloop"]
    colours = colour_map(t, "pulseloop")
    o = [f"// {HEADER.format(v=t['version'])}", "package com.pulseloop.ui.theme", "",
         "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", "",
         "/**",
         " * Gabriel Design System values for PulseLoop (dark only). PulseColors, PulseType and Motion alias",
         " * these; a screen reads PulseColors, never this object directly, so FairyMode keeps working.",
         " */",
         "object GTokens {", "    object Colors {"]
    usage = {tok["name"]: tok.get("usage", "") for tok in r["color"]}
    for name, v in colours.items():
        o += ["    " + kdoc(usage[name]), f"        val {camel(name)} = Color({argb(v['dark'])})"]
    o += ["    }", "", "    object Spacing {"]
    o += [f"        val {camel(tok['name'])} = {num(tok['value'])}.dp" for tok in r["spacing"]]
    o += ["    }", "", "    object Radius {"]
    o += [f"        val {camel(tok['name'])} = {num(tok['value'])}.dp" for tok in r["radius"]]
    o += ["    }", "", "    object Size {"]
    o += [f"        val {camel(tok['name'])} = {num(tok['value'])}.dp" for tok in r["size"]]
    o += ["    }", "", "    /** Durations in ms. */", "    object Motion {"]
    o += [f"        const val {camel(tok['name'])} = {num(tok['value'])}" for tok in r["motion"]]
    o += ["    }", "", "    /** Font sizes in sp, line heights in em. */", "    object Type {",
          "        val scale = listOf(" + ", ".join(str(s) for s in layer["typeScale"]) + ")"]
    for group in layer["type"]:
        for st in group["styles"]:
            n = camel(st["name"])
            o += [f"        const val {n}Size = {num(st['fontSize'])}",
                  f"        const val {n}LineEm = {num(st['lineHeight'])}f",
                  f"        const val {n}Weight = {int(st.get('fontWeight', 400))}"]
    d = layer["dither"]
    o += ["    }", "", "    object Dither {",
          "        val bayer4 = intArrayOf(" + ", ".join(str(x) for x in d["bayer4"]) + ")",
          f"        const val steps = {d['steps']}", "    }", "}"]
    return "\n".join(o) + "\n"


# ---- web: CSS custom properties ------------------------------------------------------------------

def css_hex(h):
    h = h.lstrip("#")
    return "#" + (h[2:] + h[:2] if len(h) == 8 else h)  # #AARRGGBB -> #RRGGBBAA


def css(t, layer_name):
    r = resolve(t, layer_name)
    layer = t["layers"][layer_name]
    colours = colour_map(t, layer_name)
    themes = layer["themes"]
    o = [f"/* {HEADER.format(v=t['version'])} */", f"/* Layer: {layer_name}. Themes: {', '.join(themes)}. */", ""]

    def block(selector, theme):
        o.append(f"{selector} {{")
        o.extend(f"  --gds-{n}: {css_hex(v[theme])};" for n, v in colours.items() if theme in v)
        o.append("}")

    first = themes[0]
    block(":root", first)
    for th in themes[1:]:
        o.append("")
        block(f'[data-theme="{th}"]', th)
        o.append(f"@media (prefers-color-scheme: {th}) {{")
        o.append(f'  :root:not([data-theme="{first}"]) {{')
        o.extend(f"    --gds-{n}: {css_hex(v[th])};" for n, v in colours.items() if th in v)
        o += ["  }", "}"]
    o += ["", ":root {", f"  --gds-font: {t['core']['type']['family']};"]
    for fam in ("spacing", "radius", "size", "motion"):
        o.extend(f"  --gds-{tok['name']}: {tok['value']};" for tok in r[fam])
    for group in layer["type"]:
        for st in group["styles"]:
            o.append(f"  --gds-text-{st['name']}: {st.get('fontWeight', 400)} {st['fontSize']}/{st['lineHeight']} var(--gds-font);")
    o.append("}")
    return "\n".join(o) + "\n"


# ---- DESIGN.md frontmatter (google-labs-code/design.md format, read by Impeccable) ---------------

def design_frontmatter(t):
    core = t["core"]
    o = ["---", f"name: {t['name']}", f"version: {t['version']}",
         "# GENERATED from tokens/tokens.json by scripts/gen_tokens.py. Edit the tokens, not this block.",
         "colors:"]
    for tok in core["color"]:
        o.append(f"  {tok['name']}: \"{tok['value']['light']}\"")
        o.append(f"  {tok['name']}-dark: \"{tok['value']['dark']}\"")
    o.append("typography:")
    for group in t["layers"]["uikit"]["type"]:
        for st in group["styles"]:
            o += [f"  {st['name']}:", "    fontFamily: Ubuntu Mono", f"    fontSize: {st['fontSize']}",
                  f"    fontWeight: {st.get('fontWeight', 400)}", f"    lineHeight: {st['lineHeight']}"]
            if "letterSpacing" in st:
                o.append(f"    letterSpacing: {st['letterSpacing']}")
    o.append("rounded:")
    o += [f"  {tok['name'].replace('radius-', '')}: {tok['value']}" for tok in core["radius"]]
    o.append("spacing:")
    o += [f"  {tok['name'].replace('space-', '')}: {tok['value']}" for tok in core["spacing"]]
    o.append("---")
    return "\n".join(o) + "\n"


def with_frontmatter(text, fm):
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4) + len("\n---\n")
        text = text[end:]
    return fm + text


def outputs(t):
    design = ROOT / "DESIGN.md"
    body = design.read_text() if design.exists() else "\n# Design System\n"
    return {
        ROOT / "generated/uikit/UiTokens.java": uikit_java(t),
        ROOT / "generated/pulseloop/GTokens.kt": pulseloop_kt(t),
        ROOT / "generated/web/uikit.css": css(t, "uikit"),
        ROOT / "generated/web/pulseloop.css": css(t, "pulseloop"),
        design: with_frontmatter(body, design_frontmatter(t)),
    }


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs(load()).items():
        rel = path.relative_to(ROOT)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(rel))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print("wrote", rel)
    if check:
        if stale:
            print("stale (run python3 scripts/gen_tokens.py):", ", ".join(stale))
            return 1
        print("generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
